// Q8 🟢 Number ko string mein convert karne ke 3 tarike likho.

// Number → String (3 Tarike) 🔷

// 3 Methods:

let num = 42;

// 1. String()
String(num)        // "42"

// 2. toString()
num.toString()     // "42"

// 3. + operator
num + ""           // "42"

// 🎯 Memory Rule

/*

V=String()      → direct convert
toString()    → variable pe call karo
num + ""      → shorthand trick

*/