// Q32 🟢 Assignment operators ka practical use karo.

/* 

=   Assign
+=  Add and assign
-=  Subtract and assign
*=  Multiply and assign
/=  Divide and assign
%=  Modulus and assign
**= Exponent and assign

*/

let score = 10;

console.log(score);
score += 10;
console.log(score);

score -= 20;
console.log(score);

score = 10
score *= 10;
console.log(score);

score /= 10;
console.log(score);

score = 99;
score %= 10;
console.log(score);

score **= 9;
console.log(score);